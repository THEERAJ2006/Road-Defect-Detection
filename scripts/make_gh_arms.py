"""Define arms F_lsk and H_eiou: single-factor LSK / EIoU ablations on stock YOLOv8s.

F_lsk: stock YOLOv8s backbone with ONE inserted row — LSKBlock after the P3/8
    downsampling conv (mirroring arm G_lsk's placement, but on the stock Conv
    backbone instead of the paper's SPD backbone). No SPD, no ASF neck, no
    C2f_Faster, stock CIoU loss. The insert shifts backbone indices >= 4 by
    +1, so every head `from` index >= 4 is remapped mechanically.
H_eiou: stock YOLOv8s with EIoU box loss (plain, Focal=False, matching arm
    I_eiou). A loss adds no parameters, so like arm D_wiou this yaml is
    identical to baseline and the loss is swapped code-side via
    src.modules.eiou.install_eiou() at train time.

Both train under runs/ablation/ with the same methodology as arms A-E
(COCO init, SGD lr0 0.01, batch 4, imgsz 640, 150 epochs, data/rdd2022-cn.yaml);
see scripts/run_ablation_gh.py.
"""

import copy
import pathlib
import sys

sys.path.insert(0, "/home/sandy/Projects/PEP-26")

from src.model import install  # noqa: E402

install()
from ultralytics.nn.tasks import DetectionModel, yaml_model_load  # noqa: E402

OUT = pathlib.Path("models/arms")
BASELINE = "models/arms/yolov8s-baseline.yaml"
LSK_AT = 4  # insert position: right after the P3/8 downsampling conv


def _remap_from(f, shift_from: int = LSK_AT, delta: int = 1):
    if isinstance(f, int):
        return f + delta if f >= shift_from else f
    return [x + delta if x >= shift_from else x for x in f]


def build_f_lsk() -> pathlib.Path:
    d = yaml_model_load(BASELINE)
    d = {k: copy.deepcopy(v) for k, v in d.items() if k in ("nc", "scales", "backbone", "head")}
    bb, hd = d["backbone"], d["head"]
    assert bb[3][2] == "Conv" and bb[3][3][0] == 256, f"expected P3 Conv@3, got {bb[3]}"
    bb.insert(LSK_AT, [-1, 1, "LSKBlock", [256]])
    for i, (f, n, m, a) in enumerate(hd):
        hd[i] = [_remap_from(f), n, m, a]
    d["scale"] = "s"
    p = OUT / "yolov8s-F_lsk.yaml"
    p.write_text(
        "# Ablation arm F_lsk: stock YOLOv8s + LSKBlock only (no SPD/neck/Faster, CIoU loss).\n"
        "# LSK row inserted after the P3/8 downsampling conv; head `from` indices >= 4 remapped +1.\n"
        "# Generated by scripts/make_gh_arms.py.\n\n"
        + __import__("yaml").safe_dump(d, sort_keys=False, default_flow_style=None)
    )
    return p


def build_h_eiou() -> pathlib.Path:
    text = pathlib.Path(BASELINE).read_text().split("\n", 3)
    p = OUT / "yolov8s-H_eiou.yaml"
    p.write_text(
        "# Ablation arm H_eiou: stock YOLOv8s + EIoU loss only (plain, Focal=False).\n"
        "# Yaml is identical to baseline; the loss is swapped code-side via\n"
        "# src.modules.eiou.install_eiou() (same convention as arm D_wiou / WIoU).\n"
        "# Generated by scripts/make_gh_arms.py.\n\n" + text[3]
    )
    return p


if __name__ == "__main__":
    base = sum(
        p.numel()
        for p in DetectionModel(
            {**yaml_model_load(BASELINE), "scale": "s"}, ch=3, nc=5, verbose=False
        ).parameters()
    )
    for name, build in (("F_lsk", build_f_lsk), ("H_eiou", build_h_eiou)):
        path = build()
        dd = yaml_model_load(str(path))
        dd["scale"] = "s"
        n = sum(p.numel() for p in DetectionModel(dd, ch=3, nc=5, verbose=False).parameters())
        mods = [t for _, _, t, _ in dd["backbone"] + dd["head"]]
        lsk = sum(1 for t in mods if t == "LSKBlock")
        print(f"{name:<8} params={n:,} (baseline {base:,}, delta {n - base:+,}) "
              f"layers={len(dd['backbone']) + len(dd['head'])} LSKBlocks={lsk}")
        if name == "H_eiou":
            assert n == base, "loss-only arm must not change parameter count"
        if name == "F_lsk":
            assert lsk == 1 and n > base, "F_lsk must add exactly one LSKBlock"
    print("wrote 2 arm yamls to", OUT)
